package commands

import (
	"bytes"
	"errors"
	"fmt"
	"io"
	"os"
	"path/filepath"
	"sort"
	"strings"

	"gopkg.in/yaml.v3"
)

const (
	agentSyncConfigRelPath = ".agents/config.yaml"
	agentSyncSchemaVersion = 1
	agentSyncHeader        = "<!-- GENERATED BY fastbuild agent:sync FROM .agents/config.yaml — DO NOT EDIT -->"
)

type agentSyncOptions struct {
	check bool
	force bool
}

type agentConfig struct {
	SchemaVersion int                          `yaml:"schema_version"`
	Instructions  string                       `yaml:"instructions"`
	SkillRoots    []string                     `yaml:"skill_roots"`
	Targets       map[string]agentTargetConfig `yaml:"targets"`
}

type agentTargetConfig struct {
	Enabled bool   `yaml:"enabled"`
	Output  string `yaml:"output"`
}

type discoveredSkill struct {
	Name        string
	Path        string
	Description string
}

type generatedAgentFile struct {
	Target  string
	RelPath string
	Content []byte
}

type agentSyncResult struct {
	Created   int
	Updated   int
	Unchanged int
	Missing   []string
	Drifted   []string
}

// AgentSyncCommand generates deterministic tool-specific agent adapters from .agents/config.yaml.
type AgentSyncCommand struct {
	writer             io.Writer
	findRoot           func() (string, error)
	suppressCompletion bool
}

func NewAgentSyncCommand() *AgentSyncCommand {
	return &AgentSyncCommand{
		writer:   os.Stdout,
		findRoot: findProjectRoot,
	}
}

func (c *AgentSyncCommand) Name() string { return "agent:sync" }
func (c *AgentSyncCommand) Description() string {
	return "Generate agent instruction adapters from .agents/config.yaml"
}
func (c *AgentSyncCommand) Usage() string { return "agent:sync [--check] [--force]" }

func (c *AgentSyncCommand) SuppressCompletionOutput() bool {
	return c.suppressCompletion
}

func (c *AgentSyncCommand) Run(args []string) error {
	c.suppressCompletion = false
	options, err := parseAgentSyncOptions(args)
	if err != nil {
		return err
	}
	c.suppressCompletion = options.check

	rootFinder := c.findRoot
	if rootFinder == nil {
		rootFinder = findProjectRoot
	}
	root, err := rootFinder()
	if err != nil {
		return err
	}

	cfg, err := loadAgentConfig(root)
	if err != nil {
		return err
	}

	files, err := renderAgentSyncFiles(root, cfg)
	if err != nil {
		return err
	}

	result, err := syncAgentFiles(root, files, options)
	if err != nil {
		return err
	}

	writer := c.writer
	if writer == nil {
		writer = os.Stdout
	}
	if options.check {
		_, _ = fmt.Fprintf(writer, "agent:sync check passed (%d files up to date)\n", result.Unchanged)
		return nil
	}
	_, _ = fmt.Fprintf(
		writer,
		"agent:sync complete: %d created, %d updated, %d unchanged\n",
		result.Created,
		result.Updated,
		result.Unchanged,
	)
	return nil
}

func parseAgentSyncOptions(args []string) (agentSyncOptions, error) {
	var options agentSyncOptions

	for index := 0; index < len(args); index++ {
		argument := args[index]
		switch {
		case argument == "--check":
			options.check = true
		case argument == "--force":
			options.force = true
		case argument == "--env" || argument == "--env-file":
			index++
			if index >= len(args) {
				return agentSyncOptions{}, fmt.Errorf("%s requires a value", argument)
			}
		case strings.HasPrefix(argument, "--env=") || strings.HasPrefix(argument, "--env-file="):
			// Global options are resolved by cmd/fastbuild before command dispatch.
		default:
			return agentSyncOptions{}, fmt.Errorf("unknown agent:sync option %q", argument)
		}
	}

	return options, nil
}

func loadAgentConfig(root string) (agentConfig, error) {
	configPath := filepath.Join(root, filepath.FromSlash(agentSyncConfigRelPath))
	raw, err := os.ReadFile(configPath)
	if err != nil {
		return agentConfig{}, fmt.Errorf("read %s: %w", agentSyncConfigRelPath, err)
	}

	var cfg agentConfig
	if err := yaml.Unmarshal(raw, &cfg); err != nil {
		return agentConfig{}, fmt.Errorf("parse %s: %w", agentSyncConfigRelPath, err)
	}
	if err := validateAgentConfig(cfg); err != nil {
		return agentConfig{}, err
	}
	return cfg, nil
}

func validateAgentConfig(cfg agentConfig) error {
	if cfg.SchemaVersion != agentSyncSchemaVersion {
		return fmt.Errorf("%s: unsupported schema_version %d (expected %d)", agentSyncConfigRelPath, cfg.SchemaVersion, agentSyncSchemaVersion)
	}
	if strings.TrimSpace(cfg.Instructions) == "" {
		return fmt.Errorf("%s: instructions path is required", agentSyncConfigRelPath)
	}
	if len(cfg.Targets) == 0 {
		return fmt.Errorf("%s: at least one target must be configured", agentSyncConfigRelPath)
	}

	targetNames := make([]string, 0, len(cfg.Targets))
	for name := range cfg.Targets {
		targetNames = append(targetNames, name)
	}
	sort.Strings(targetNames)

	for _, name := range targetNames {
		target := cfg.Targets[name]
		if !target.Enabled {
			continue
		}
		output := strings.TrimSpace(target.Output)
		if output == "" {
			return fmt.Errorf("%s: target %q output path is required", agentSyncConfigRelPath, name)
		}
		cleaned := filepath.Clean(filepath.FromSlash(output))
		if filepath.IsAbs(cleaned) || cleaned == ".." || strings.HasPrefix(cleaned, ".."+string(filepath.Separator)) {
			return fmt.Errorf("%s: target %q output path %q must stay within repository root", agentSyncConfigRelPath, name, output)
		}
	}
	return nil
}

func renderAgentSyncFiles(root string, cfg agentConfig) ([]generatedAgentFile, error) {
	if err := validateAgentConfig(cfg); err != nil {
		return nil, err
	}

	activeRoots, skills, err := discoverAgentSkills(root, cfg.SkillRoots)
	if err != nil {
		return nil, err
	}

	targetNames := make([]string, 0, len(cfg.Targets))
	for name := range cfg.Targets {
		targetNames = append(targetNames, name)
	}
	sort.Strings(targetNames)

	files := make([]generatedAgentFile, 0, len(targetNames))
	for _, name := range targetNames {
		target := cfg.Targets[name]
		if !target.Enabled {
			continue
		}
		relPath := filepath.ToSlash(filepath.Clean(filepath.FromSlash(strings.TrimSpace(target.Output))))
		content := renderTargetAdapter(name, cfg.Instructions, activeRoots, skills)
		files = append(files, generatedAgentFile{
			Target:  name,
			RelPath: relPath,
			Content: []byte(content),
		})
	}
	return files, nil
}

func discoverAgentSkills(root string, skillRoots []string) ([]string, []discoveredSkill, error) {
	activeRoots := make([]string, 0, len(skillRoots))
	seenRoots := make(map[string]struct{}, len(skillRoots))
	seenSkills := make(map[string]struct{})
	skills := make([]discoveredSkill, 0)

	for _, rawRoot := range skillRoots {
		trimmed := strings.TrimSpace(rawRoot)
		if trimmed == "" {
			continue
		}
		relRoot := filepath.ToSlash(filepath.Clean(filepath.FromSlash(trimmed)))
		if _, exists := seenRoots[relRoot]; exists {
			continue
		}
		seenRoots[relRoot] = struct{}{}

		absRoot := filepath.Join(root, filepath.FromSlash(relRoot))
		info, err := os.Stat(absRoot)
		if err != nil {
			if errors.Is(err, os.ErrNotExist) {
				continue
			}
			return nil, nil, fmt.Errorf("stat skill root %s: %w", relRoot, err)
		}
		if !info.IsDir() {
			continue
		}
		activeRoots = append(activeRoots, relRoot)

		entries, err := os.ReadDir(absRoot)
		if err != nil {
			return nil, nil, fmt.Errorf("read skill root %s: %w", relRoot, err)
		}
		for _, entry := range entries {
			if !entry.IsDir() {
				continue
			}
			skillFile := filepath.Join(absRoot, entry.Name(), "SKILL.md")
			if !fileExists(skillFile) {
				continue
			}
			relSkillPath := filepath.ToSlash(filepath.Join(relRoot, entry.Name(), "SKILL.md"))
			if _, exists := seenSkills[relSkillPath]; exists {
				continue
			}
			seenSkills[relSkillPath] = struct{}{}

			name, description := parseSkillFrontmatter(skillFile, entry.Name())
			skills = append(skills, discoveredSkill{
				Name:        name,
				Path:        relSkillPath,
				Description: description,
			})
		}
	}

	sort.Slice(skills, func(i, j int) bool {
		if skills[i].Name == skills[j].Name {
			return skills[i].Path < skills[j].Path
		}
		return skills[i].Name < skills[j].Name
	})

	return activeRoots, skills, nil
}

func parseSkillFrontmatter(skillFilePath, fallbackName string) (string, string) {
	raw, err := os.ReadFile(skillFilePath)
	if err != nil {
		return fallbackName, ""
	}
	lines := strings.Split(strings.ReplaceAll(string(raw), "\r\n", "\n"), "\n")
	if len(lines) < 3 || strings.TrimSpace(lines[0]) != "---" {
		return fallbackName, ""
	}

	end := -1
	for i := 1; i < len(lines); i++ {
		if strings.TrimSpace(lines[i]) == "---" {
			end = i
			break
		}
	}
	if end == -1 {
		return fallbackName, ""
	}

	var fm struct {
		Name        string `yaml:"name"`
		Description string `yaml:"description"`
	}
	if err := yaml.Unmarshal([]byte(strings.Join(lines[1:end], "\n")), &fm); err != nil {
		return fallbackName, ""
	}
	name := strings.TrimSpace(fm.Name)
	if name == "" {
		name = fallbackName
	}
	return name, strings.TrimSpace(fm.Description)
}

func renderTargetAdapter(targetName, instructions string, activeRoots []string, skills []discoveredSkill) string {
	var b strings.Builder

	if targetName == "cursor" {
		b.WriteString("---\n")
		b.WriteString("description: FastBuild repository agent routing and conventions\n")
		b.WriteString("alwaysApply: true\n")
		b.WriteString("---\n\n")
	}

	b.WriteString(agentSyncHeader)
	b.WriteString("\n\n")
	fmt.Fprintf(&b, "# FastBuild Agent Adapter (%s)\n\n", formatTargetTitle(targetName))
	fmt.Fprintf(&b, "Canonical instructions live in `%s`.\n", instructions)
	b.WriteString("Read it before making changes, and read the nearest unit `AGENTS.md` (`api/AGENTS.md`, `apps/web/AGENTS.md`, `apps/admin/AGENTS.md`) when editing that unit.\n\n")

	b.WriteString("## Quick Context\n\n")
	b.WriteString("Run `cd api && go run ./cmd/fastbuild context --changed` (or `fastbuild context --changed`) to inspect impacted units, active contracts, and minimal verification commands for the current working tree.\n\n")

	b.WriteString("## Skill Roots\n\n")
	if len(activeRoots) == 0 {
		b.WriteString("- (none discovered)\n")
	} else {
		for _, root := range activeRoots {
			fmt.Fprintf(&b, "- `%s`\n", root)
		}
	}
	b.WriteString("\n")

	b.WriteString("## Discovered Skills\n\n")
	if len(skills) == 0 {
		b.WriteString("- (none discovered)\n")
	} else {
		for _, skill := range skills {
			if skill.Description != "" {
				fmt.Fprintf(&b, "- `%s` (`%s`): %s\n", skill.Name, skill.Path, skill.Description)
			} else {
				fmt.Fprintf(&b, "- `%s` (`%s`)\n", skill.Name, skill.Path)
			}
		}
	}

	return b.String()
}

func formatTargetTitle(targetName string) string {
	switch strings.ToLower(strings.TrimSpace(targetName)) {
	case "claude":
		return "Claude"
	case "cursor":
		return "Cursor"
	case "codex":
		return "Codex"
	default:
		if targetName == "" {
			return "Agent"
		}
		return strings.ToUpper(targetName[:1]) + targetName[1:]
	}
}

func isManagedAgentFile(content []byte) bool {
	normalized := strings.ReplaceAll(string(content), "\r\n", "\n")
	for _, line := range strings.Split(normalized, "\n") {
		if strings.TrimSpace(line) == agentSyncHeader {
			return true
		}
	}
	return false
}

func syncAgentFiles(root string, files []generatedAgentFile, opts agentSyncOptions) (agentSyncResult, error) {
	var result agentSyncResult

	for _, file := range files {
		absPath := filepath.Join(root, filepath.FromSlash(file.RelPath))
		existing, err := os.ReadFile(absPath)
		if err != nil {
			if !errors.Is(err, os.ErrNotExist) {
				return result, fmt.Errorf("read %s: %w", file.RelPath, err)
			}
			if opts.check {
				result.Missing = append(result.Missing, file.RelPath)
				continue
			}
			if mkErr := os.MkdirAll(filepath.Dir(absPath), 0o755); mkErr != nil {
				return result, fmt.Errorf("create directory for %s: %w", file.RelPath, mkErr)
			}
			if writeErr := os.WriteFile(absPath, file.Content, 0o644); writeErr != nil {
				return result, fmt.Errorf("write %s: %w", file.RelPath, writeErr)
			}
			result.Created++
			continue
		}

		if bytes.Equal(existing, file.Content) {
			result.Unchanged++
			continue
		}

		if opts.check {
			result.Drifted = append(result.Drifted, file.RelPath)
			continue
		}

		if !isManagedAgentFile(existing) && !opts.force {
			return result, fmt.Errorf(
				"refusing to overwrite unmanaged file %s (missing generated header; pass --force to overwrite)",
				file.RelPath,
			)
		}

		if writeErr := os.WriteFile(absPath, file.Content, 0o644); writeErr != nil {
			return result, fmt.Errorf("write %s: %w", file.RelPath, writeErr)
		}
		result.Updated++
	}

	if opts.check && (len(result.Missing) > 0 || len(result.Drifted) > 0) {
		problems := make([]string, 0, len(result.Missing)+len(result.Drifted))
		for _, path := range result.Missing {
			problems = append(problems, "missing: "+path)
		}
		for _, path := range result.Drifted {
			problems = append(problems, "drifted: "+path)
		}
		sort.Strings(problems)
		return result, fmt.Errorf("agent adapters out of sync (%s); run 'fastbuild agent:sync'", strings.Join(problems, "; "))
	}

	return result, nil
}
